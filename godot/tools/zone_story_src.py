def N(yue, zh=None): return ["旁白", yue, zh if zh is not None else yue]      # 旁白（書面語）
def G(yue, zh=None): return ["告示", yue, zh if zh is not None else yue]      # 告示（書面語）

def _where(ci, zid):
    for w, bs in ZIDS[ci]["wild"].items():
        if zid in bs: return w, bs.index(zid)
    return None, -1

def Z(ci, kind, zid, title, lines, style="talk", art=None, extra=None):
    bid = "zs%d_%s" % (ci, kind) + ("_" + zid if zid else "")
    w = {"t": "zone", "kind": kind}
    if zid: w["id"] = zid
    if kind.startswith("boss_"):
        z, i = _where(ci, zid)
        w["z"] = z; w["bi"] = i
    b = {"id": bid, "when": w}
    if kind != "map_enter": b["need"] = {"after": ["zs%d_map_enter" % ci]}
    sc = {"style": style, "title": title, "lines": lines}
    if style in ("talk", "news", "notice", "radio"): sc["bg"] = BG[ci]
    if extra: sc.update(extra)
    b["scene"] = sc
    if art: b["art"] = art
    ZBEATS.setdefault(ci, []).append(b)
    return b


