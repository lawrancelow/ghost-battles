def build():
    names = _zones()
    bosses = {}
    for bid, d in B.items():
        o = {"name": names.get(bid, [bid, bid])}
        o.update(d)
        bosses[bid] = o
    return {"v": 1, "bosses": bosses, "cap": CAP, "raid": RAID}

def write():
    out = build()
    fp = D("data", "nat", "taunts.json")
    with open(fp, "w", encoding="utf-8") as f:
        f.write(json.dumps(out, ensure_ascii=False, indent=1))
        f.write("\n")
    # 女主版：只增／改呢度嘅句，其他條目唔郁（格式同 outpost_build：indent=1、冇尾換行）
    ff = D("data", "fem.json")
    fem = json.load(open(ff, encoding="utf-8"))
    if any(fem.get(k) != v for k, v in FEM.items()):
        fem.update(FEM)
        with open(ff, "w", encoding="utf-8") as f:
            f.write(json.dumps(fem, ensure_ascii=False, indent=1))
    n = sum(len(d[k]) for d in B.values() for k in ("lose", "idle", "rematch", "defeat"))
    n += sum(len(z[k]) for c in CAP.values() for z in c.values() for k in ("lose", "idle", "defeat"))
    n += sum(len(v) for v in RAID.values())
    print("taunts.json：王 %d、資源區 %d、告急 %d 關；共 %d 句；女版 %d 條" % (
        len(B), sum(len(c) for c in CAP.values()), len(RAID), n, len(FEM)))

if __name__ == "__main__":
    write()
