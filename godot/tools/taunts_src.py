def _zones():
    z = json.load(open(D("data", "nat", "zones.json"), encoding="utf-8"))
    names = {}
    for ci, m in z["maps"].items():
        for zz in m["zones"]:
            for b in zz.get("bosses", []): names[b["id"]] = list(b["n"])
    return names

